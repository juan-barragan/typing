#!/usr/bin/env python3
"""Create the common-word and letter-pair asset from a word frequency list.

The list has one "word count" pair per line, most frequent first, e.g.
https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt
Only words already in data/words.js are kept, so the dictionary stays the source of truth.
"""
import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('source')
parser.add_argument('--words', type=int, default=10000, help='common words to keep')
parser.add_argument('--pairs', type=int, default=40, help='letter pairs to keep')
args = parser.parse_args()
dictionary = set(json.loads(re.search(r'=(\[.*\]);', (ROOT / 'data' / 'words.js').read_text()).group(1)))
counts = {}
for line in Path(args.source).read_text().splitlines():
    word, _, count = line.strip().lower().partition(' ')
    # Skip fragments such as "'s" rather than stripping them into new words.
    if re.fullmatch('[a-z]+', word) and word in dictionary and word not in counts:
        counts[word] = int(count)
common = list(counts)[:args.words]
# Pairs inside words, weighted by how often each word is typed.
pairs = Counter()
for word, count in counts.items():
    for pair in zip(word, word[1:]):
        pairs[''.join(pair)] += count
top_pairs = [pair for pair, _ in pairs.most_common(args.pairs)]
target = ROOT / 'data' / 'common.js'
target.write_text('// Generated by scripts/build_frequency.py from the FrequencyWords English list (CC BY-SA 4.0).\n'
                  + 'window.TYPEWELL_COMMON=' + json.dumps(common, separators=(',', ':')) + ';\n'
                  + 'window.TYPEWELL_PAIRS=' + json.dumps(top_pairs, separators=(',', ':')) + ';\n')
print(f'Wrote {len(common):,} common words and {len(top_pairs)} letter pairs to {target}')
