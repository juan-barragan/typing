#!/usr/bin/env python3
"""Create the real-sentence asset from Tatoeba's English sentences.

Download https://downloads.tatoeba.org/exports/per_language/eng/eng_sentences.tsv.bz2
(id, language, text per line; .bz2 or uncompressed). Requires data/common.js, so run
scripts/build_frequency.py first.
"""
import argparse
import bz2
import json
import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Practice order after capitals, ending with digits ("0-9"); each gets a guaranteed share of sentences.
UNITS = [*'.,\'?!-";:', '0-9']
CONTRACTIONS = {'s', 't', 'll', 're', 've', 'd', 'm'}
parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('source')
parser.add_argument('--sentences', type=int, default=10000, help='sentences to keep')
parser.add_argument('--vocabulary', type=int, default=5000, help='most common words a sentence may use')
parser.add_argument('--per-mark', type=int, default=600, help='sentences reserved for each mark and for digits')
args = parser.parse_args()
common = json.loads(re.search(r'TYPEWELL_COMMON=(\[.*?\]);', (ROOT / 'data' / 'common.js').read_text()).group(1))
vocabulary = set(common[:args.vocabulary])


def everyday(sentence):
    # Every word, and each part of a contraction such as don't, must be common.
    for word in re.findall(r"[A-Za-z']+", sentence):
        stem, *endings = word.lower().split("'")
        if stem not in vocabulary or any(ending not in CONTRACTIONS for ending in endings):
            return False
    return True


source = Path(args.source)
lines = (bz2.open(source, 'rt', encoding='utf-8') if source.suffix == '.bz2' else source.open(encoding='utf-8'))
candidates = []
for line in lines:
    sentence = line.rstrip('\n').split('\t')[-1].replace('’', "'")
    if (20 <= len(sentence) <= 90 and sentence[0].isupper() and '  ' not in sentence
            and re.fullmatch(r"[A-Za-z0-9 .,'?!;:\-\"]+", sentence) and everyday(sentence)):
        candidates.append(sentence)
random.seed(0)
random.shuffle(candidates)
# Tatoeba leans heavily on "Tom" and "Mary"; keep them to a small share.
names = re.compile(r'\b(Tom|Mary)\b')
named_limit = args.sentences // 10
uses = lambda sentence, unit: any(c.isdigit() for c in sentence) if unit == '0-9' else unit in sentence
chosen, seen, named = [], set(), 0
for unit in [*reversed(UNITS), None]:
    quota = args.per_mark if unit else args.sentences
    taken = 0
    for sentence in candidates:
        if len(chosen) >= args.sentences or taken >= quota:
            break
        if sentence in seen or (unit and not uses(sentence, unit)):
            continue
        if names.search(sentence):
            if named >= named_limit:
                continue
            named += 1
        chosen.append(sentence)
        seen.add(sentence)
        taken += 1
chosen.sort()
target = ROOT / 'data' / 'sentences.js'
target.write_text('// Generated by scripts/build_sentences.py from Tatoeba (https://tatoeba.org), CC BY 2.0 FR.\n'
                  + 'window.TYPEWELL_SENTENCES=' + json.dumps(chosen, separators=(',', ':')) + ';\n')
print(f'Wrote {len(chosen):,} of {len(candidates):,} suitable sentences to {target}')
