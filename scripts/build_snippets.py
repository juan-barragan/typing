#!/usr/bin/env python3
"""Create the code-mode asset from snippets/python.py and snippets/typescript.ts.

Snippets are separated by a "# %%" (Python) or "// %%" (TypeScript) line, and each
starts with a comment stating its goal. Every snippet is checked on its own: Python
with compile(), TypeScript with `tsc --strict` (skipped with a warning when tsc is
not installed).
"""
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = {'python': ('python.py', '#'), 'typescript': ('typescript.ts', '//')}
MAX_COLUMNS = 79
MAX_LINES = 20


def split(path: Path, comment: str) -> list[str]:
    snippets, current = [], None
    for line in path.read_text().splitlines():
        if line.strip() == f'{comment} %%':
            current = []
            snippets.append(current)
        elif current is not None:
            current.append(line)
    # Text before the first marker is the file's own header, not a snippet.
    return ['\n'.join(lines).strip('\n') for lines in snippets]


def problems(snippet: str, comment: str) -> list[str]:
    lines = snippet.split('\n')
    found = []
    if not lines[0].startswith(comment + ' '):
        found.append('must start with a comment stating its goal')
    if not 3 <= len(lines) <= MAX_LINES:
        found.append(f'has {len(lines)} lines; use 3 to {MAX_LINES}')
    for number, line in enumerate(lines, 1):
        if not line.isascii() or '\t' in line:
            found.append(f'line {number}: use ASCII and spaces only')
        if line != line.rstrip():
            found.append(f'line {number}: trailing whitespace')
        if len(line) > MAX_COLUMNS:
            found.append(f'line {number}: longer than {MAX_COLUMNS} columns')
    return found


def check_typescript(snippets: list[str]) -> list[str]:
    tsc = shutil.which('tsc')
    if not tsc:
        print('warning: tsc not found, TypeScript snippets were not type-checked', file=sys.stderr)
        return []
    with tempfile.TemporaryDirectory() as folder:
        files = []
        for index, snippet in enumerate(snippets, 1):
            files.append(f'snippet {index:02}.ts')
            (Path(folder) / files[-1]).write_text(snippet + '\n')
        # Each file is its own module, so snippets can't lean on each other.
        result = subprocess.run([tsc, '--noEmit', '--strict', '--target', 'es2022', '--lib', 'es2022,dom',
                                 '--moduleDetection', 'force', '--skipLibCheck', *files],
                                capture_output=True, text=True, cwd=folder)
        return [line for line in result.stdout.splitlines() if 'error' in line]


output, failures = {}, []
for language, (name, comment) in LANGUAGES.items():
    snippets = split(ROOT / 'snippets' / name, comment)
    for index, snippet in enumerate(snippets, 1):
        failures += [f'{name} snippet {index}: {problem}' for problem in problems(snippet, comment)]
        if language == 'python':
            try:
                compile(snippet, f'{name} snippet {index}', 'exec')
            except SyntaxError as error:
                failures.append(f'{name} snippet {index}: {error}')
    if language == 'typescript':
        failures += [f'{name} {error}' for error in check_typescript(snippets)]
    output[language] = snippets
if failures:
    sys.exit('\n'.join(failures))
target = ROOT / 'data' / 'snippets.js'
target.write_text('// Generated by scripts/build_snippets.py from snippets/python.py and snippets/typescript.ts.\n'
                  + 'window.TYPEWELL_SNIPPETS=' + json.dumps(output, separators=(',', ':')) + ';\n')
print(f'Wrote {", ".join(f"{len(s)} {lang}" for lang, s in output.items())} snippets to {target}')
